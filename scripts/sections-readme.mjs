// Writes the README's "Jump to a game section" directory from the sections every activity declares (its sections.ts:
// each section's name, group and extra links), so nobody edits the README by hand when they add or rename a section.
//   node scripts/sections-readme.mjs           rewrite the README between the sections:start/end markers
//   node scripts/sections-readme.mjs --check   fail if the README is out of date (npm run verify)
import { readFileSync, writeFileSync } from 'node:fs'
import { loadWorld, worldLink } from './world-registry.mjs'

const SITE = 'https://neb636.github.io/Kaylee-Gamepack/'
const START = '<!-- sections:start (generated by scripts/sections-readme.mjs from each sections.ts: edit those, not this) -->'
const END = '<!-- sections:end -->'

// `:` and `;` stay readable too (cup=forest:1,steps:2; door=a,b;c,d), like the commas.
const url = (place, activity, section, params) => `${SITE}${worldLink(place, activity, section, params).replace(/%3A/g, ':').replace(/%3B/g, ';')}`
const md = (label, href) => `[${label}](${href})`

/** "Baan Chang: the cafe" under the Baan Chang bullet reads "The cafe" (the stage name isn't repeated). */
function withoutGroup(label, group) {
  if (!group || !label.toLowerCase().startsWith(`${group.toLowerCase()}: `)) return label
  const rest = label.slice(group.length + 2)
  return rest[0].toUpperCase() + rest.slice(1)
}

/** One activity's README block: a heading, then a bullet per entry (grouped), or one `·` line for a short plain one. */
function activityBlock(place, a) {
  const def = a.sections
  const heading = a.kind === 'finale' ? `Finale${def?.title ? `: ${def.title}` : ''}` : (def?.title ?? a.name)
  const works = a.kind === 'works' ? ' (in the works)' : ''
  const head = `**${heading}**${works}${def?.note ? ` (${def.note})` : ''}`
  if (!def) return a.kind === 'finale' ? null : `${head}: no sections yet`

  // A finale's link collects every stamp first, like the section index's (PlaceFrame reads ?stamps=all).
  const base = a.kind === 'finale' ? { stamps: 'all' } : {}
  const entries = def.sections.flatMap((s) =>
    (s.links ?? [{ label: s.name }]).map((l) => {
      const link = (x) => (x.bare ? `${SITE}#/world/${place}` : url(place, a.id, s.id, { ...base, ...x.params, ...x.flags }))
      const also = l.also?.length ? ` (${l.also.map((x) => md(x.label, link(x))).join(', ')})` : ''
      return { group: s.group, text: `${md(withoutGroup(l.label, s.group), link(l))}${also}`, plain: !l.also?.length }
    }),
  )
  if (entries.every((e) => !e.group && e.plain)) return `${head}: ${entries.map((e) => e.text).join(' · ')}`

  const lines = [head, '']
  let group
  for (const e of entries) {
    if (e.group !== group) {
      group = e.group
      if (group) lines.push(`- **${group}**`)
    }
    lines.push(`${e.group ? '  ' : ''}- ${e.text}`)
  }
  return lines.join('\n')
}

export async function directory() {
  const out = []
  for (const p of await loadWorld()) {
    out.push(`### ${p.name}`)
    for (const a of p.activities) {
      const block = activityBlock(p.id, a)
      if (block) out.push(block)
    }
  }
  return out.join('\n\n')
}

const readme = readFileSync('README.md', 'utf8')
const from = readme.indexOf(START)
const to = readme.indexOf(END)
if (from < 0 || to < from) {
  console.error(`README.md needs the ${START} and ${END} markers around the section directory.`)
  process.exit(1)
}
const next = `${readme.slice(0, from + START.length)}\n\n${await directory()}\n\n${readme.slice(to)}`
if (process.argv.includes('--check')) {
  if (next !== readme) {
    console.error('README.md\'s section directory is out of date: run `node scripts/sections-readme.mjs` and commit it.')
    process.exit(1)
  }
  console.log('README section directory is up to date.')
} else if (next !== readme) {
  writeFileSync('README.md', next)
  console.log('README.md section directory rewritten.')
} else console.log('README section directory already up to date.')
